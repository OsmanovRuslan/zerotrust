package ru.donstu.zerotrust.core.model;

/**
 * Режим применения решения, задаваемый политикой.
 *
 * <p>Режим {@link #MONITOR} нужен для безопасного внедрения модуля в работающую систему:
 * сначала месяц наблюдения за журналом решений, потом настройка порогов по собранным данным,
 * и только потом включение {@link #ENFORCE}. Иначе первый же день работы модуля с неподходящими
 * порогами означает лавину step-up у законных пользователей.
 */
public enum Enforcement {

    /** Решение применяется: STEP_UP и DENY останавливают вызов. */
    ENFORCE,

    /**
     * Решение вычисляется и пишется в журнал с {@code enforced = false}, но вызов выполняется.
     * Блокировки, RBAC и проверка владельца (шаги 1–5 алгоритма решения) применяются всегда,
     * в том числе в этом режиме.
     */
    MONITOR
}
