package ru.donstu.zerotrust.core.model;

/**
 * Тип события безопасности и его тяжесть по умолчанию.
 *
 * <p>Тяжесть s — это штраф, который событие добавляет к накопленному штрафу P в формуле
 * репутации. Отрицательная тяжесть восстанавливает репутацию: успешный step-up
 * — единственное событие, которое работает «в плюс», потому что человек доказал, что это он.
 *
 * <p>Значения здесь — <b>умолчания</b>. Действующие величины берутся из настройки
 * {@code zerotrust.factors.reputation.severities}: администратор может ужесточить
 * или ослабить реакцию, не меняя код. Значения в перечислении нужны, чтобы модуль работал
 * с пустой конфигурацией и чтобы тяжести по умолчанию были зафиксированы в коде и в тестах.
 */
public enum SecurityEventType {

    /** Неверный код TOTP или отказ от step-up у провайдера. */
    STEP_UP_FAILED(0.10),

    /** Успешное подтверждение вторым фактором: частично восстанавливает репутацию. */
    STEP_UP_SUCCEEDED(-0.10),

    /** Попытка доступа к чужому объекту — BOLA, уязвимость №1 OWASP API Security Top 10. */
    OWNERSHIP_VIOLATION(0.25),

    /** Сработало правило с действием {@link Action#DENY}. */
    RULE_DENIED(0.15),

    /** Превышено ограничение частоты {@code @RateLimit}. */
    RATE_LIMIT_EXCEEDED(0.15),

    /** Оценка доверия оказалась ниже низкого порога θ_L — step-up уже не предлагается. */
    LOW_TRUST_DENIED(0.20),

    /** Невозможное перемещение: скорость между двумя вызовами ≥ 900 км/ч. */
    IMPOSSIBLE_TRAVEL(0.30),

    /** Дрейф доверия внутри сессии: признак перехвата сессии. */
    SESSION_DRIFT(0.10),

    /** Нет нужной роли или разрешения. Тяжесть мала: обычно это просто ошибка навигации. */
    RBAC_DENIED(0.05),

    /** Вызов с устройства, которое владелец или администратор отозвал. */
    REVOKED_DEVICE_USED(0.30),

    /** Вызов от заблокированного пользователя: только запись в журнал, репутацию не меняет. */
    BLOCKED_ACCESS_ATTEMPT(0.0);

    private final double defaultSeverity;

    SecurityEventType(double defaultSeverity) {
        this.defaultSeverity = defaultSeverity;
    }

    /**
     * Тяжесть события по умолчанию.
     *
     * @return величина, добавляемая к накопленному штрафу P; может быть отрицательной
     */
    public double defaultSeverity() {
        return defaultSeverity;
    }
}
