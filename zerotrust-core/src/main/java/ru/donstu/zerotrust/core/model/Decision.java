package ru.donstu.zerotrust.core.model;

/**
 * Итоговое решение о доступе, которое принимает PDP.
 *
 * <p>Перенесено из прототипа ({@code demo}) без изменений: три значения оказались достаточными
 * и в полной модели. Соответствие HTTP-ответам задаётся не здесь, а в {@link DecisionReason}:
 * у одного решения {@code DENY} статусы разные (403, 404, 429, 503) в зависимости от причины.
 */
public enum Decision {

    /** Доступ разрешён, защищённый метод выполняется. */
    ALLOW,

    /** Нужна адаптивная (step-up) аутентификация: клиент получает 401 и повторяет вызов после подтверждения. */
    STEP_UP,

    /** Доступ запрещён. */
    DENY
}
