package ru.donstu.zerotrust.core.spi;

import java.util.Map;

/**
 * Атрибуты субъекта из хранилища приложения: отдел, тариф, лимит — всё, на что
 * ссылаются правила ABAC.
 *
 * <p>Модуль не требует менять формат хранения пользователей: приложение отдаёт атрибуты одним
 * методом. Результат кешируется, поэтому метод вызывается при промахе кеша, а не на каждый вызов.
 * Ошибка провайдера не отклоняет вызов: атрибуты считаются пустыми, в лог пишется WARN.
 */
public interface SubjectAttributesProvider {

    /** Атрибуты субъекта; пустая карта, если ничего не известно. */
    Map<String, Object> load(String subjectId);

    /** Порядок объединения, если провайдеров несколько: меньший порядок применяется первым. */
    default int order() {
        return 0;
    }
}
