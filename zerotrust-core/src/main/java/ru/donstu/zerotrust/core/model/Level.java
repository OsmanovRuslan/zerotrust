package ru.donstu.zerotrust.core.model;

/**
 * Уровень проверки защищённой операции.
 *
 * <p>Уровень определяет базовый требуемый порог доверия θ_level и то, считается ли доверие вообще:
 *
 * <ul>
 *   <li>{@link #AUTH_ONLY} — аннотация {@code @Authenticated} или режим {@code secure-by-default}:
 *       проверяются личность, блокировки, роли, владелец и правила, но оценка доверия
 *       <b>не вычисляется</b> и дрейф сессии не проверяется (шаг 6 алгоритма решения);</li>
 *   <li>{@link #NORMAL} — {@code @RequireTrust} по умолчанию: требуется высокий порог θ_H;</li>
 *   <li>{@link #CRITICAL} — {@code @RequireTrust(level = CRITICAL)}: требуется критический
 *       порог θ_C, а срок действия step-up-подтверждения короче
 *       ({@code step-up.critical-ttl}).</li>
 * </ul>
 */
public enum Level {

    /** Только личность и доступ, без оценки доверия. */
    AUTH_ONLY,

    /** Обычная операция: базовый порог — высокий θ_H. */
    NORMAL,

    /** Критическая операция: базовый порог — критический θ_C. */
    CRITICAL
}
