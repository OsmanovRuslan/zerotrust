package ru.donstu.zerotrust.core.factor;

/** Состояние устройства пользователя (таблица zt_device). */
public enum DeviceStatus {

    /** Устройство увидели впервые. */
    NEW,

    /** Устройство встречалось достаточно часто и давно. */
    KNOWN,

    /** Доверенное: подтверждено step-up на этом устройстве или администратором. */
    TRUSTED,

    /** Отозвано пользователем или администратором: вызов с него сразу отклоняется. */
    REVOKED
}
