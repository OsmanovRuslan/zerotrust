package ru.donstu.zerotrust.core.model;

/**
 * Действие, которое предписывает сработавшее правило условий.
 *
 * <p>Действия перечислены от самого строгого к самому мягкому; в этом же порядке они
 * комбинируются, если на одном вызове сработало несколько правил (шаг 7 алгоритма решения):
 * достаточно одного {@link #DENY}, чтобы вызов был отклонён.
 *
 * <p>«Правило не сработало» отдельным значением не обозначается: в {@link RuleOutcome}
 * этому случаю соответствует {@code action == null} (см. {@link RuleOutcome#pass(String)}).
 */
public enum Action {

    /** Запретить вызов: решение DENY с причиной {@link DecisionReason#DENY_RULE}. */
    DENY,

    /** Потребовать подтверждение вторым фактором независимо от значения оценки доверия. */
    STEP_UP,

    /**
     * Поднять требуемый порог доверия до {@code raiseTo} — та самая динамическая критичность
     * операции: один и тот же метод требует разного доверия в зависимости
     * от аргументов вызова.
     */
    RAISE,

    /** Ничего не менять, только записать срабатывание в журнал решений. */
    LOG
}
